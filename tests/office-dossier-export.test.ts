import { beforeEach, describe, expect, it, vi } from 'vitest';
import { documentFixture } from './fixtures/office-dossier';
import { HttpError } from '@/src/server/errors';
const mocks = vi.hoisted(() => ({
  read: vi.fn(),
  render: vi.fn(),
  user: vi.fn(),
  audit: vi.fn(),
  rate: vi.fn(),
}));
vi.mock('@/src/server/db/office', () => ({ getDossierData: mocks.read }));
vi.mock('@/src/server/pdf/office-dossier', () => ({ renderOfficeDossier: mocks.render }));
vi.mock('@/src/server/db/client', () => ({ db: { auditLog: { create: mocks.audit } } }));
vi.mock('@/src/server/security', () => ({
  requireUser: mocks.user,
  rateLimit: mocks.rate,
  HttpError,
  failure: (error: unknown) =>
    Response.json(
      { error: error instanceof HttpError ? error.message : 'invalid_input' },
      { status: error instanceof HttpError ? error.status : 400 },
    ),
}));
import { GET } from '@/app/api/v1/portfolios/[id]/dossier/route';
const call = (query = '') =>
  GET(new Request(`http://localhost/api/v1/portfolios/board-1/dossier${query}`), {
    params: Promise.resolve({ id: 'board-1' }),
  });
beforeEach(() => {
  vi.resetAllMocks();
  mocks.user.mockResolvedValue({ id: 'demo-client', role: 'CLIENT' });
  mocks.read.mockImplementation(async () => documentFixture());
  mocks.render.mockResolvedValue(Buffer.from('%PDF-sensitive-content'));
  mocks.audit.mockResolvedValue({});
});
describe('dossier authorization at byte release', () => {
  it('permits unchanged owner-only download with private cache and disposition headers', async () => {
    const response = await call('?locale=ar&currency=USD');
    expect(response.status).toBe(200);
    expect(response.headers.get('cache-control')).toBe('private, no-store');
    expect(response.headers.get('content-disposition')).toContain('attachment');
    expect(await response.text()).toBe('%PDF-sensitive-content');
    expect(mocks.user).toHaveBeenCalledTimes(2);
    expect(mocks.read).toHaveBeenCalledTimes(2);
    expect(mocks.audit).toHaveBeenCalledTimes(1);
  });
  it('discards generated bytes if a grant was revoked while Chromium rendered', async () => {
    mocks.read
      .mockResolvedValueOnce(documentFixture())
      .mockRejectedValueOnce(new HttpError(409, 'portfolio_changed'));
    const response = await call();
    expect(response.status).toBe(409);
    expect(await response.text()).not.toContain('%PDF');
    expect(mocks.audit).not.toHaveBeenCalled();
  });
  it('discards generated bytes if the owner role or account disappears', async () => {
    mocks.user
      .mockResolvedValueOnce({ id: 'demo-client', role: 'CLIENT' })
      .mockRejectedValueOnce(new HttpError(401, 'unauthorized'));
    const response = await call();
    expect(response.status).toBe(401);
    expect(await response.text()).not.toContain('%PDF');
  });
  it('requires review when content changes even if the same board remains visible', async () => {
    const changed = documentFixture();
    changed.stories[0].facts[0].value = 90000000;
    mocks.read.mockResolvedValueOnce(documentFixture()).mockResolvedValueOnce(changed);
    const response = await call();
    expect(response.status).toBe(409);
    expect(await response.json()).toEqual({ error: 'dossier_review_required' });
    expect(mocks.audit).not.toHaveBeenCalled();
  });
  it('passes an explicit visible-set review to both authorization reads', async () => {
    expect((await call('?reviewVisible=true&arabicIndicDigits=false')).status).toBe(200);
    for (const args of mocks.read.mock.calls) {
      expect(args[2]).toEqual({ arabicIndicDigits: false });
      expect(args[3]).toEqual({ reviewVisible: true });
    }
  });
  it('accepts the same numeric digit preference as Office read endpoints', async () => {
    expect((await call('?arabicIndicDigits=1')).status).toBe(200);
    expect(mocks.read.mock.calls[0][2]).toEqual({ arabicIndicDigits: true });
  });
  it.each(['?reviewVisible=anything', '?arabicIndicDigits=yes', '?url=https://evil.example'])(
    'rejects malformed export parameters before rendering: %s',
    async (query) => {
      expect((await call(query)).status).toBe(400);
      expect(mocks.render).not.toHaveBeenCalled();
    },
  );
});
